        // Used only on the built-in tray menu, never on user calendar names or task text.
        public static void RefreshMenu(ToolStripItemCollection items)
        {
            foreach (ToolStripItem item in items)
            {
                string original = item.Tag as string;
                if (original == null)
                {
                    original = item.Text;
                    original = Original(original);
                    item.Tag = original;
                }
                item.Text = T(original);
            }
        }
