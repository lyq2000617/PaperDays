        public static string T(string source, string language)
        {
            if (source == null || language == "zh-CN") return source;
            if (language == "zh-TW") return Traditional(source);
            string[] values; string value;
            if (all.TryGetValue(source,out values)) return values[language == "ko" ? 1 : language == "ja" ? 2 : 0];
            return en.TryGetValue(source,out value) ? value : source;
        }
        public static string Original(string value)
        {
            foreach (var pair in all) foreach (string translation in pair.Value) if (translation == value) return pair.Key;
            foreach (var pair in en) if (pair.Value == value) return pair.Key;
            return value;
        }
        public static string ShortDay(int day) { return Culture.DateTimeFormat.AbbreviatedDayNames[(day + 1) % 7]; }
        public static string Country(string code,string chinese)
        {
            int index=Array.IndexOf(Calendars.Codes,code);
            if (index<0) return chinese;
            if (Language=="ko") return new[] { "중국","대한민국","일본","미국","영국","독일","프랑스","캐나다","호주","뉴질랜드" }[index];
            if (Language=="ja") return new[] { "中国","韓国","日本","米国","英国","ドイツ","フランス","カナダ","オーストラリア","ニュージーランド" }[index];
            return Language=="en" ? new RegionInfo(code).EnglishName : T(chinese);
        }
